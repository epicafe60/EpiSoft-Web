import { addDays } from './pos';

// R-CPT-08 (extension) — periods under which the sales of the cash sessions are proposed to the
// treasurer as one accounting entry: a week (as the old EpiCompta did, "Ventes Semaine 25") or a day.

export type PeriodGrouping = 'WEEK' | 'DAY';

export interface SalesPeriod {
  /** Stable identifier of the period, stored on the generated entry to avoid duplicates. */
  key: string;
  from: string;
  to: string;
  label: string;
}

const dayOfWeek = (iso: string) => new Date(`${iso}T12:00:00Z`).getUTCDay(); // 0 = Sunday

/** ISO week number of a date. */
function isoWeek(iso: string): number {
  const d = new Date(`${iso}T12:00:00Z`);
  const day = (d.getUTCDay() + 6) % 7; // Monday = 0
  d.setUTCDate(d.getUTCDate() - day + 3); // Thursday of this week
  const firstThursday = new Date(Date.UTC(d.getUTCFullYear(), 0, 4, 12));
  const fday = (firstThursday.getUTCDay() + 6) % 7;
  firstThursday.setUTCDate(firstThursday.getUTCDate() - fday + 3);
  return 1 + Math.round((d.getTime() - firstThursday.getTime()) / (7 * 86_400_000));
}

const fr = (iso: string) => iso.split('-').reverse().join('/');

/**
 * The period holding `date`. A week runs Monday to Sunday and is cut at the turn of the year,
 * so that one entry never straddles two fiscal years.
 */
export function salesPeriodOf(date: string, grouping: PeriodGrouping): SalesPeriod {
  if (grouping === 'DAY') {
    return { key: `D:${date}`, from: date, to: date, label: `Ventes du ${fr(date)}` };
  }
  const monday = addDays(date, -((dayOfWeek(date) + 6) % 7));
  const sunday = addDays(monday, 6);
  const year = date.slice(0, 4);
  const from = monday < `${year}-01-01` ? `${year}-01-01` : monday;
  const to = sunday > `${year}-12-31` ? `${year}-12-31` : sunday;
  return {
    key: `W:${from}`,
    from,
    to,
    label: `Ventes semaine ${isoWeek(date)} (${fr(from)} au ${fr(to)})`,
  };
}

/**
 * Default first day to propose: the day after the last entry that was not generated by this
 * tool (the old accounting, manual entries), or the first session when there is none.
 */
export function defaultProposalStart(
  lastManualEntryDate: string | null,
  firstSessionDate: string | null,
): string | null {
  if (lastManualEntryDate) return addDays(lastManualEntryDate, 1);
  return firstSessionDate;
}

export type ProposalState = 'NEW' | 'UP_TO_DATE' | 'OUTDATED_DRAFT' | 'DIFFERS_VALIDATED';

/** What to do with a period given the entry already generated for it, if any. */
export function proposalState(
  existing: { status: 'DRAFT' | 'VALIDATED' } | null,
  sameLines: boolean,
): ProposalState {
  if (!existing) return 'NEW';
  if (sameLines) return 'UP_TO_DATE';
  return existing.status === 'DRAFT' ? 'OUTDATED_DRAFT' : 'DIFFERS_VALIDATED';
}

/** Order-independent signature of planned lines, to tell whether an entry is still current. */
export function linesSignature(
  lines: readonly { account: string; debitCents: number; creditCents: number }[],
): string {
  return lines
    .map((l) => `${l.account}|${l.debitCents}|${l.creditCents}`)
    .sort()
    .join(';');
}
